import { autoUpdater } from 'electron-updater'
import type { BrowserWindow } from 'electron'
import type { UpdateStatus } from '../shared/api'
import {
  describeUpdateError,
  disabledUpdateMessage,
  isCheckBlocked,
  type UpdateDisabledReason,
} from '../shared/update-status'
import type { Logger } from './logger'

/** Re-exported so existing main-process imports keep working. */
export { disabledUpdateMessage }
export type { UpdateDisabledReason }

export interface UpdateServiceOptions {
  enabled: boolean
  currentVersion: string
  platform?: NodeJS.Platform
  /** Why updates are disabled; drives the macOS dev/unsigned message. */
  disabledReason?: UpdateDisabledReason
  getWindow: () => BrowserWindow | null
  logger: Logger
}

/**
 * In-app auto-update backed by electron-updater + GitHub Releases.
 *
 * The packaged app reads app-update.yml (generated by electron-builder), checks
 * the latest public release, downloads the NSIS update, and can restart into
 * it. Development, Linux and macOS builds without a Developer ID signature
 * report "disabled" instead of touching the network.
 */
export class UpdateService {
  private readonly options: UpdateServiceOptions
  private status: UpdateStatus
  private checking = false
  private lastLoggedState: string | null = null

  constructor(options: UpdateServiceOptions) {
    this.options = options
    const platform = options.platform ?? process.platform
    this.status = {
      state: options.enabled ? 'idle' : 'disabled',
      currentVersion: options.currentVersion,
      canCheck: options.enabled,
      message: options.enabled ? undefined : disabledUpdateMessage(platform, options.disabledReason),
    }
  }

  init(): void {
    if (!this.options.enabled) {
      this.options.logger.info(`Auto-update disabled: ${this.status.message ?? 'not available'}`)
      return
    }

    autoUpdater.logger = {
      info: (message?: unknown) => this.options.logger.info(String(message ?? '')),
      warn: (message?: unknown) => this.options.logger.warn(String(message ?? '')),
      error: (message?: unknown) => this.options.logger.error(String(message ?? '')),
      debug: (message: string) => this.options.logger.info(`[updater] ${message}`),
    }
    autoUpdater.autoDownload = true
    autoUpdater.autoInstallOnAppQuit = true
    autoUpdater.autoRunAppAfterInstall = true
    autoUpdater.allowPrerelease = false
    autoUpdater.allowDowngrade = false

    autoUpdater.on('checking-for-update', () => {
      this.set({ state: 'checking', message: undefined })
    })
    autoUpdater.on('update-available', (info) => {
      this.options.logger.info(`Update available: ${info.version}`)
      this.set({ state: 'available', availableVersion: info.version, message: undefined })
    })
    autoUpdater.on('update-not-available', () => {
      this.set({
        state: 'idle',
        availableVersion: undefined,
        progress: undefined,
        bytesPerSecond: undefined,
        transferred: undefined,
        total: undefined,
        message: 'You are up to date.',
      })
    })
    autoUpdater.on('download-progress', (progress) => {
      this.set({
        state: 'downloading',
        progress: Math.max(0, Math.min(100, progress.percent)),
        bytesPerSecond: progress.bytesPerSecond,
        transferred: progress.transferred,
        total: progress.total,
        message: undefined,
      })
    })
    autoUpdater.on('update-downloaded', (info) => {
      this.options.logger.info(`Update downloaded: ${info.version}`)
      this.set({
        state: 'downloaded',
        availableVersion: info.version,
        progress: 100,
        message: 'Restart PhoneDeck to finish installing.',
      })
    })
    autoUpdater.on('update-cancelled', () => {
      this.set({
        state: 'idle',
        progress: undefined,
        bytesPerSecond: undefined,
        transferred: undefined,
        total: undefined,
        message: 'Update download was cancelled.',
      })
    })
    autoUpdater.on('error', (error) => {
      this.options.logger.warn(`Update error: ${error.message}`)
      this.set({
        state: 'error',
        progress: undefined,
        bytesPerSecond: undefined,
        transferred: undefined,
        total: undefined,
        message: describeUpdateError(error),
      })
    })

    this.options.logger.info('Auto-update enabled (GitHub Releases feed)')
    // Keep the initial status available to the renderer even if it has not
    // mounted yet; App.tsx calls getUpdateStatus() on startup.
    this.push()
  }

  checkOnStartup(): void {
    if (!this.options.enabled) return
    const timer = setTimeout(() => void this.check(), 5000)
    timer.unref?.()
  }

  async check(): Promise<UpdateStatus> {
    if (!this.options.enabled) return this.getStatus()
    if (this.checking || isCheckBlocked(this.status)) return this.getStatus()

    this.checking = true
    this.set({
      state: 'checking',
      availableVersion: undefined,
      progress: undefined,
      bytesPerSecond: undefined,
      transferred: undefined,
      total: undefined,
      message: undefined,
    })
    try {
      await autoUpdater.checkForUpdates()
    } catch (error) {
      this.options.logger.warn(`Update check failed: ${(error as Error).message}`)
      this.set({ state: 'error', message: describeUpdateError(error) })
    } finally {
      this.checking = false
    }
    return this.getStatus()
  }

  install(): void {
    if (!this.options.enabled || this.status.state !== 'downloaded') return
    this.options.logger.info('Installing downloaded update and restarting')
    this.set({ message: 'Restarting to install…' })
    setImmediate(() => {
      try {
        autoUpdater.quitAndInstall(false, true)
      } catch (error) {
        this.options.logger.warn(`Could not launch the installer: ${(error as Error).message}`)
        this.set({ state: 'error', message: describeUpdateError(error) })
      }
    })
  }

  getStatus(): UpdateStatus {
    return { ...this.status }
  }

  private set(patch: Partial<UpdateStatus>): void {
    this.status = { ...this.status, ...patch, canCheck: this.options.enabled }
    if (this.status.state !== this.lastLoggedState) {
      this.lastLoggedState = this.status.state
      this.options.logger.info(`Update state: ${this.status.state}`)
    }
    this.push()
  }

  private push(): void {
    const window = this.options.getWindow()
    if (window && !window.isDestroyed()) {
      window.webContents.send('phonedek:update-status', this.getStatus())
    }
  }
}
